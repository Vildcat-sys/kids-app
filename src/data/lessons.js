/**
 * data/lessons.js — 探究课堂（数据驱动的 5 阶段互动课）
 *
 * ═══════════════════════════════════════════════════════════════
 * 两条内容来源，汇成同一节课
 * ═══════════════════════════════════════════════════════════════
 *   1. LESSONS —— 手写精编课（当前 21 节，7 板块 × 3）。
 *      这些课把「引入→探究→应用→表达→检验」五阶段每个环节都写全，
 *      有家里真能做的小实验、生活例子和拓展。
 *   2. buildLesson(item) —— 自动引擎。
 *      任何知识点（data/*.js 的 item）哪怕没手写课，也能由它的
 *      lead / facts[3] / quiz 自动拼出一节 5 阶段课。
 *      这样「探究课堂」对全部 160 个知识点开放，不再只有少数几节。
 *
 *   lesson.js 永远只调 buildLesson(item)：手写命中就用手写，否则自动生成。
 *   对外的 hasLesson / getLesson 仍只认手写表（行为契约见 tests/lesson.test.mjs）。
 *
 * ═══════════════════════════════════════════════════════════════
 * 五阶段 / 环节（引入 → 探究 → 应用 → 表达 → 检验）
 * ═══════════════════════════════════════════════════════════════
 *   引入  explore      主动探索（先自己看/点，不给答案）
 *   引入  conjecture  问题猜想（不判对错，只引导「去看看」）
 *   探究  prepare     收集准备（材料清单，可缺省）
 *   探究  experiment  实验/逐点演示（facts 配绘本图 + 旁白）
 *   探究  interactive 互动问答（答错可重试，不一次结束）
 *   应用  life        生活中的应用
 *   应用  expand      知识拓展（翻卡）
 *   表达  teach       当小老师（优先录音，不支持降级跟读复述）
 *   检验  test        单元测
 *   检验  report      探索报告（星 + 金币，结算只一次）
 *
 * 写作纪律：实验家里真能做；猜想不判对错；表达给句式脚手架不给标准答案。
 */

